from __future__ import annotations

from pathlib import Path

import pandas as pd

from faults.injectors import generate_telemetry
from fronthaul_sim.simulator import SimConfig
from telemetry.features import window_features


def build_dataset(config: dict, out_dir: Path) -> pd.DataFrame:
    out_dir.mkdir(parents=True, exist_ok=True)
    sim_cfg = SimConfig(
        seed=config["seed"],
        time_error_budget_ns=config["time_error_budget_ns"],
        **config["sim"],
        **config.get("oscillator", {}),
    )
    telemetry = generate_telemetry(sim_cfg, int(config["dataset"]["scenarios_per_type"]))
    telemetry.to_csv(out_dir / "splane_telemetry.csv", index=False)
    windows = window_features(telemetry, float(config["dataset"]["window_s"]), float(config["dataset"]["step_s"]))
    windows.to_csv(out_dir / "splane_windows.csv", index=False)
    write_datasheet(out_dir / "DATASHEET.md", windows)
    return windows


def write_datasheet(path: Path, windows: pd.DataFrame) -> None:
    counts = windows["label"].value_counts().to_dict()
    path.write_text(
        "# S-Plane Timing Dataset Datasheet\n\n"
        "Synthetic labelled dataset generated by a deterministic pure-Python PTP/SyncE clock-servo simulator.\n\n"
        f"Rows: {len(windows)}\n\n"
        f"Label counts: {counts}\n\n"
        "Labels: `healthy`, `H0` benign timing fault, `H1` timing attack.\n\n"
        "Limitations: no hardware timestamping, no real O-RU/O-DU, no production traffic. The dataset is intended for "
        "reproducible research prototyping and resume/demo evidence, not certification.\n",
        encoding="utf-8",
    )
